function buildItem(entry) {
  const record = byFirestoreId(entry.firestoreId);
  const depictedDate = { minYear: record.year, maxYear: record.year };
  const seg = record.image_url.split("/").pop();
  const sourceUrl = `https://commons.wikimedia.org/wiki/File:${seg}`;

  return {
    schemaVersion: 1,
    id: entry.id,
    status: "approved",
    workType: entry.workType,
    title: record.title,
    artistOrCreator: entry.artistOrCreator,
    depictedDate,
    creationDate: entry.creationDate,
    location: { placeId: entry.placeId, acceptedPlaceIds: [] },
    classification: {
      region: entry.region,
      difficulty: entry.difficulty,
      landmarkCategory: entry.landmarkCategory,
      tags: entry.tags,
    },
    clues: { region: entry.region, era: `${Math.floor(record.year / 10) * 10}s`, country: record.country },
    media: { originalPath: entry.originalPath, focalPoint: null },
    attribution: {
      source: "Wikimedia Commons",
      license: entry.license,
      sourceUrl,
      creditText: entry.creditText,
    },
    context: entry.context,
    contentWarning: null,
    curation: { approvedBy: "andrew", approvedAt: NOW, notes: "M2 seed batch; license verified against Commons file page before approval." },
    importSource: `firestore:${entry.firestoreId}`,
    createdAt: record.createTime,
    updatedAt: NOW,
  };
}

const items = SEED.map(buildItem);
fs.writeFileSync(path.join(sourceDir, "items.json"), JSON.stringify(items, null, 2));
